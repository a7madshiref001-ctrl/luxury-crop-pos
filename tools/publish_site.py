# -*- coding: utf-8 -*-
# بينسخ الكاشير لموقع محصول فاخر تحت /pos/ ويكتب قواعد الحماية بتاعته في _headers
import base64, hashlib, io, os, re, shutil

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
SITE = os.path.abspath(os.path.join(ROOT, '..', 'luxury-crop-system'))
OUT = os.path.join(SITE, 'pos')
PAGES = ['index.html', 'app.html', 'kds.html', 'kiosk.html', 'screen.html']
DB = 'qckjfyupxwctfizqdbxe.supabase.co'

config = io.open(os.path.join(ROOT, 'assets', 'config.js'), encoding='utf-8').read()
V = re.search(r"version: '(\d+)'", config).group(1)

if os.path.isdir(OUT):
    shutil.rmtree(OUT)
os.makedirs(OUT)
shutil.copytree(os.path.join(ROOT, 'assets'), os.path.join(OUT, 'assets'))

SW = """/* Network first, so the cashier always runs the newest version; the saved copy is used only without internet. */
const CACHE = 'lcpos-v%s';
const WAIT_MS = 4000;
self.addEventListener('install', () => self.skipWaiting());
self.addEventListener('activate', (e) => e.waitUntil((async () => {
  for (const k of await caches.keys()) if (k.startsWith('lcpos-') && k !== CACHE) await caches.delete(k);
  await self.clients.claim();
})()));
const clean = (p) => (p.endsWith('/') ? p + 'index' : p.replace(/\\.html$/, ''));
self.addEventListener('fetch', (e) => {
  const r = e.request;
  const u = new URL(r.url);
  if (r.method !== 'GET' || u.origin !== location.origin || !u.pathname.includes('/pos/')) return;
  const key = clean(u.pathname) + u.search;
  e.respondWith((async () => {
    const c = await caches.open(CACHE);
    const net = fetch(r).then((res) => { if (res.ok && res.type === 'basic') c.put(key, res.clone()); return res; });
    const hit = await c.match(key);
    if (!hit) return net;
    return Promise.race([net.catch(() => hit), new Promise((ok) => setTimeout(() => ok(hit), WAIT_MS))]);
  })());
});
""" % V
io.open(os.path.join(OUT, 'sw.js'), 'w', encoding='utf-8', newline='\n').write(SW)

hashes = []
for page in PAGES:
    s = io.open(os.path.join(ROOT, page), encoding='utf-8').read().replace('\r\n', '\n')
    io.open(os.path.join(OUT, page), 'w', encoding='utf-8', newline='\n').write(s)
    for m in re.finditer(r'<script>(.*?)</script>', s, re.S):
        h = "'sha256-%s'" % base64.b64encode(hashlib.sha256(m.group(1).encode('utf-8')).digest()).decode()
        if h not in hashes:
            hashes.append(h)

csp = ("default-src 'self'; script-src 'self' %s; style-src 'self' 'unsafe-inline'; img-src 'self' data: blob: https://%s; font-src 'self' data:; "
       "connect-src 'self' https://%s wss://%s; media-src 'self' blob:; worker-src 'self'; object-src 'none'; base-uri 'none'; form-action 'none'; frame-ancestors 'none'") % (' '.join(hashes), DB, DB, DB)
assert len(csp) < 1900, len(csp)
BLOCK = "# BEGIN POS (generated by luxury-crop-pos/tools/publish_site.py)\n/pos/*\n  X-Robots-Tag: noindex, nofollow\n  Cache-Control: no-cache\n  Content-Security-Policy: %s\n# END POS\n" % csp

p = os.path.join(SITE, '_headers')
s = io.open(p, encoding='utf-8').read().replace('\r\n', '\n')
s = re.sub(r'\n?# BEGIN POS.*?# END POS\n', '', s, flags=re.S).rstrip('\n') + '\n\n' + BLOCK
io.open(p, 'w', encoding='utf-8', newline='\n').write(s)
print('published to', OUT, 'v' + V, 'inline scripts', len(hashes), 'csp', len(csp))
